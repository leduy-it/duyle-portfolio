test('terminal fills viewport, outside click and reset restore compact size on mobile and desktop',async({page})=>{
  for(const width of [375,1280]){
    await page.setViewportSize({width,height:812})
    await page.goto('/')
    await page.getByRole('button',{name:'Maximize window',exact:true}).click()
    const dialog=page.locator('[data-terminal-window][data-maximized="true"]')
    await expect(dialog).toBeVisible()
    const box=await dialog.boundingBox()
    expect(box?.width).toBeGreaterThan(width*.85)
    expect(box?.height).toBeGreaterThan(730)
    expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    await page.mouse.click(4,4)
    await expect(page.locator('[data-maximized="true"]')).toHaveCount(0)
    await page.getByRole('button',{name:'Maximize window',exact:true}).click()
    await page.getByRole('button',{name:'Reset window size'}).click()
    await expect(page.locator('[data-maximized="true"]')).toHaveCount(0)
  }
})
test('secret discovery and pet discovery remain separate; trigger needs the name twice',async({page})=>{
  await page.clock.install()
  await page.goto('/life')
  await expect(page.locator('.gracie-launcher')).toBeVisible()
  await page.clock.runFor(30000)
  await expect(page.getByRole('status',{name:'Hidden feature hint'})).toBeVisible()
  await page.clock.runFor(5000)
  await expect(page.getByRole('status',{name:'Hidden feature hint'})).toContainText('leduy leduy')
  await page.getByRole('button',{name:'Dismiss hidden feature hint'}).click()
  await page.clock.runFor(60000)
  await expect(page.getByRole('complementary',{name:'Pets suggestion'})).toBeVisible()
  await page.keyboard.type('leduy')
  await expect(page.getByRole('heading',{name:'🎁 Mystery Box'})).toHaveCount(0)
  await page.keyboard.type(' leduy')
  await expect(page.getByRole('heading',{name:'🎁 Mystery Box'})).toBeVisible()
})
