import {expect,test} from 'playwright/test'
test.use({channel:'chrome'})
test.beforeEach(async({page})=>{
  await page.route('**/api/track',route=>route.fulfill({json:{ok:true}}))
  await page.route('**/api/contact',route=>route.fulfill({json:{available:false}}))
  await page.route('**/api/chat',route=>{
    const body=route.request().postDataJSON()
    if(body.mode) return route.fulfill({json:{reply:'I would like to discuss an OCR project.'}})
    const text="[Duy's agent]\n\nThe most handsome — according to this biased bunny. Here are his photos. [[card:profile-portrait]] [[card:life-leaf-portrait]] [[card:life-outside]] [Life](/life) [bad](javascript:alert(1))"
    return route.fulfill({contentType:'text/event-stream',body:`data: ${JSON.stringify({delta:text})}\n\nevent: done\ndata: [DONE]\n\n`})
  })
})
test('rich terminal replies preview actual photos, reject unsafe links, preserve draft on navigation',async({page})=>{
  await page.goto('/')
  const input=page.locator('#terminal-chat-input')
  await input.fill('Show me photos of Duy')
  await input.press('Enter')
  const window=page.locator('[data-terminal-window]')
  await expect(window.locator('[data-chat-card]')).toHaveCount(4)
  await expect(window.locator('a[href^="javascript:"]')).toHaveCount(0)
  await window.getByRole('button',{name:'Preview image: Duy, in person'}).click()
  await expect(page.locator('dialog[open].chat-media-dialog')).toBeVisible()
  await page.getByRole('button',{name:'Close preview'}).click()
  await input.fill('my unsent follow-up')
  await window.locator('a.chat-inline-link[href="/life"]').click()
  await expect(page).toHaveURL(/\/life$/)
  await expect(page.getByRole('button',{name:'Resume chat'})).toBeVisible()
  await page.getByRole('button',{name:'Resume chat'}).click()
  await expect(page).toHaveURL(/#terminal-chat/)
  await expect(page.locator('#terminal-chat-input')).toHaveValue('my unsent follow-up')
  await expect(page.locator('[data-terminal-window]')).toContainText('The most handsome')
})
